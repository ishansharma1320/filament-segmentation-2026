#!/usr/bin/env python3
"""Assemble notebooks/submission.ipynb from the src/ modules.

The Kaggle kernel gets ONE notebook file and no repo, so every module is pasted in
as a code cell, in dependency order. Cells share a single namespace, which makes the
`from config import IMG_SIZE`-style sibling imports meaningless there: this script
strips them (and only them) during assembly. Everything else is byte-identical to src/.

Never edit the notebook by hand. Change src/, rerun this, push.

Usage: python3 scripts/build_notebook.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "src"
OUT = REPO / "notebooks" / "submission.ipynb"

# Dependency order. A cell may only use names defined in cells above it.
MODULES = ["config", "data", "rle", "metric", "postprocess", "dataset", "model", "evaluate",
           "views", "detector", "refiner", "cascade", "pipeline"]

_SIBLING = re.compile(rf"^\s*(from|import)\s+({'|'.join(MODULES)})\b")

HEADER_MD = """\
# Solar Filament Segmentation 2026 — assembled from `src/`

Generated by `scripts/build_notebook.py` — **do not edit here**; the repo is the source
of truth. One cell per module: config → data → rle → metric → postprocess → dataset →
model → evaluate → detector → refiner → cascade → pipeline, then the runner.

**Two modes, decided by what is attached.** With a dataset of `fold*_best.pt`
checkpoints attached: inference only. Without one: train grouped folds until the time
budget, save checkpoints + OOF prob maps, sweep post-processing on OOF, write the
fold-ensemble `submission.csv`. A placeholder submission is written first.

Metric: Panoptic Quality (IoU > 0.5 match), reproduced in `metric` from the organiser's
self-evaluation notebook (azimahmadzadeh/self-evaluation-notebook).
"""

# Standalone: installs the one missing dependency (internet must be ON for training
# pushes; pretrained encoder weights need it too).
BOOTSTRAP = """\
# --- bootstrap: dependencies ------------------------------------------------------------
import subprocess, sys
for mod, pkg in (("segmentation_models_pytorch", "segmentation-models-pytorch"), ("ultralytics", "ultralytics"),
                 ("rfdetr", "rfdetr[train]"), ("pytorch_lightning", "rfdetr[train]")):
    try:
        __import__(mod)
    except ImportError:
        subprocess.run([sys.executable, "-m", "pip", "install", "-q", pkg], check=False)
import segmentation_models_pytorch as smp
import ultralytics
import rfdetr
print("smp", smp.__version__, "ultralytics", ultralytics.__version__, "rfdetr", getattr(rfdetr, "__version__", "?"))
"""

RUNNER = """\
# --- run ------------------------------------------------------------------------------
run()
"""


def strip_sibling_imports(text: str) -> str:
    """Drop `from <module> import ...` lines (incl. parenthesised continuations)."""
    out, skip_until_close = [], False
    for line in text.splitlines():
        if skip_until_close:
            if ")" in line:
                skip_until_close = False
            continue
        if _SIBLING.match(line):
            if "(" in line and ")" not in line:
                skip_until_close = True
            continue
        out.append(line)
    return "\n".join(out).strip() + "\n"


def cell(kind: str, text: str) -> dict:
    lines = text.splitlines(keepends=True)
    if kind == "markdown":
        return {"cell_type": "markdown", "metadata": {}, "source": lines}
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
            "source": lines}


def main():
    cells = [cell("markdown", HEADER_MD), cell("code", BOOTSTRAP)]
    for name in MODULES:
        src = strip_sibling_imports((SRC / f"{name}.py").read_text())
        cells.append(cell("code", f"# === src/{name}.py ===\n{src}"))
    cells.append(cell("code", RUNNER))
    nb = {
        "nbformat": 4, "nbformat_minor": 5,
        "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python",
                                    "name": "python3"},
                     "language_info": {"name": "python", "version": "3.11"}},
        "cells": cells,
    }
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(json.dumps(nb, ensure_ascii=False, indent=1) + "\n")
    n_lines = sum(len(c["source"]) for c in cells)
    print(f"wrote {OUT.relative_to(REPO)}: {len(cells)} cells, {n_lines} source lines")


if __name__ == "__main__":
    main()
